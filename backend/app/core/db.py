from collections.abc import Iterator
from datetime import datetime
from enum import StrEnum
from typing import Annotated, Any, ClassVar

from fastapi import Depends
from pgvector.psycopg import register_vector
from sqlalchemy import (
    BigInteger,
    DateTime,
    Enum,
    Identity,
    MetaData,
    Text,
    create_engine,
    event,
    func,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, Session, mapped_column, sessionmaker

from app.core.config import get_settings

engine = create_engine(get_settings().database_url, pool_pre_ping=True)
SessionLocal = sessionmaker(engine, expire_on_commit=False)


@event.listens_for(engine, "connect")
def _register_vector(dbapi_connection, _connection_record) -> None:
    # The `vector` type only exists once the first migration has run.
    cursor = dbapi_connection.cursor()
    cursor.execute("SELECT 1 FROM pg_type WHERE typname = 'vector'")
    if cursor.fetchone():
        register_vector(dbapi_connection)
    cursor.close()


# Stable, explicit constraint names so autogenerated migrations stay reviewable.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    # Postgres: `text` rather than length-limited varchar (see supabase-postgres-best-practices).
    type_annotation_map: ClassVar[dict[Any, Any]] = {str: Text}


def id_column() -> Mapped[int]:
    """`bigint generated always as identity` primary key."""
    return mapped_column(BigInteger, Identity(always=True), primary_key=True)


def str_enum(enum_cls: type[StrEnum]) -> Enum:
    """Store a StrEnum as text with a CHECK constraint on its values (no PG enum to migrate)."""
    return Enum(
        enum_cls,
        native_enum=False,
        create_constraint=True,
        length=None,
        values_callable=lambda members: [m.value for m in members],
    )


class TimestampMixin:
    """`created_at` / `updated_at` on every table (docs/ARCHITECTURE.md)."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )


def get_session() -> Iterator[Session]:
    with SessionLocal() as session:
        yield session


SessionDep = Annotated[Session, Depends(get_session)]
